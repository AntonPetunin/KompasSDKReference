struct IAPIObjectIID
{
  uint8_t data[37];

  bool operator==(const IAPIObjectIID & other) const { return !std::memcmp(data, other.data, 36); }
};


////////////////////////////////////////////////////////////////////////////////
//
/// Базовый объект API.
/*
  \ingroup 
*/
////////////////////////////////////////////////////////////////////////////////
struct IAPIObject
{
  /// Деструктор
  virtual ~IAPIObject() = default;

  virtual void AddRef() = 0;
  virtual void Release() = 0;
  virtual IAPIObject * QueryInterface(IAPIObjectIID id) = 0;
};

constexpr IAPIObjectIID IID_IAPIObject{"11473080-d3ff-4d2c-82fa-f746284274b4"};


////////////////////////////////////////////////////////////////////////////////
//
/// Оболочка для объектов API.
/*
  \ingroup 
*/
////////////////////////////////////////////////////////////////////////////////
template<class T, IAPIObjectIID objectId>
struct SmartPtr
{
  using Type = T;

  T * obj = nullptr;

  SmartPtr() = default;
  SmartPtr(const SmartPtr<T, objectId> & other) { Set(other.obj, true); }

  template<class V, IAPIObjectIID vObjectId>
  SmartPtr(const SmartPtr<V, vObjectId> & other)
  {
    Set(other.obj, true);
  }

  SmartPtr(SmartPtr<T, objectId> && other)
    : obj(other.obj)
  {
    other.obj = nullptr;
  }

  SmartPtr(T * object) { Set(object, true); }

  template<class V>
  SmartPtr(V * object)
  {
    Set(object, true);
  }

  ~SmartPtr() { Set(nullptr, false); }

  T * Get() const { return obj; }

  auto operator<=>(const SmartPtr<T, objectId> & other) const = default;

  SmartPtr<T, objectId> & operator=(const SmartPtr<T, objectId> & other)
  {
    if (*this != other)
      Set(other.obj, true);

    return *this;
  }

  SmartPtr<T, objectId> & operator=(SmartPtr<T, objectId> && other)
  {
    if (*this != other)
    {
      Set(other.obj, false);
      other.obj = nullptr;
    }

    return *this;
  }

  template<class V, IAPIObjectIID vObjectId>
  SmartPtr<T, objectId> & operator=(const SmartPtr<V, vObjectId> & other)
  {
    Set(other.obj, true);
    return *this;
  }

  T * operator->() { return obj; }
  T * operator->() const { return obj; }
  T & operator*() { return *obj; }
  T & operator*() const { return *obj; }

  operator bool() const { return obj != nullptr; }
  bool operator!() { return obj == nullptr; }

  template<class V, IAPIObjectIID vObjectId>
  bool operator==(const SmartPtr<V, vObjectId> & other) const
  {
    if (obj == other.obj)
      return true;

    if (!obj || !other)
      return false;

    return obj->QueryInterface(IID_IAPIObject) == other->QueryInterface(IID_IAPIObject);
  }

  template<class V, IAPIObjectIID vObjectId>
  bool operator!=(const SmartPtr<V, vObjectId> & other) const
  {
    return !operator==(other);
  }

  bool operator<(const SmartPtr<T, objectId> & other) const { return Get() < other.Get(); }

  void Clear() { Set(nullptr, false); }

  bool IsEmpty() const { return obj == nullptr; }

private:
  void Set(T * other, bool addRef)
  {
    if (obj)
      obj->Release();

    obj = other;

    if (obj && addRef)
      obj->AddRef();
  }

  template<class V>
  void Set(V * other, bool addRef)
  {
    if (obj)
      obj->Release();

    if (other)
      obj = static_cast<T *>(other->QueryInterface(objectId));
    else
      obj = nullptr;

    if (obj && addRef)
      obj->AddRef();
  }
};

